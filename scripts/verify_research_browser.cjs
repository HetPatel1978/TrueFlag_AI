/* Actual native UI/API verification. No mocked responses or paid requests. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const { randomUUID } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const { chromium, request } = createRequire(path.join(root, 'frontend/package.json'))('@playwright/test');
const directory = JSON.parse(fs.readFileSync(path.join(root, 'runtime/windows-native/current.json'))).directory;
const state = JSON.parse(fs.readFileSync(path.join(directory, 'state.json')));
const logins = JSON.parse(fs.readFileSync(path.join(directory, 'login.json')));
const onboarding = JSON.parse(fs.readFileSync(path.join(directory, 'academic-demo/onboarding.json')));
const caseId = onboarding.cases.priority;
const base = `http://127.0.0.1:${state.frontend_port}`;
const output = path.join(directory, `research-browser-${randomUUID()}`);
fs.mkdirSync(output);
let stage = 'initialization';
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
  const page = await context.newPage(); page.setDefaultTimeout(15000);
  const api = await request.newContext({ baseURL: base });
  const report = { case_id: caseId, live_requests: 0, production_approval: false };
  try {
    stage = 'login';
    await page.goto(base);
    await page.getByLabel('Username', { exact: true }).fill('windowsadmin');
    await page.getByLabel('Password', { exact: true }).fill(logins.windowsadmin.password);
    const signed = page.waitForResponse(r => r.url().endsWith('/api/v1/auth/session') && r.request().method() === 'POST');
    await page.getByRole('button', { name: /Sign in/ }).click();
    assert.equal((await signed).status(), 200);
    stage = 'research-panel';
    await page.goto(`${base}/#/cases/${caseId}/investigation`);
    const region = page.getByRole('region', { name: 'Regulatory Research / Unapproved', exact: true });
    await region.waitFor();
    const notice = 'AI-assisted academic research demonstration. Regulatory sources have not completed independent compliance approval.';
    await region.getByText(notice, { exact: true }).waitFor();
    assert.equal(await page.getByText('No authorized provider is available.', { exact: true }).count(), 0);
    stage = 'prepare-exact-request';
    // Generate prepares the exact request for review. This script never clicks Approve.
    const reviewRegion = page.getByRole('region', { name: 'AI Request Review', exact: true });
    const generate = page.getByRole('button', { name: /^(Generate AI Investigation|Refresh Request)$/ });
    stage = 'wait-review-or-generate';
    const waitStart = Date.now();
    await reviewRegion.or(generate).first().waitFor({ timeout: 60000 });
    report.review_or_generate_visible_ms = Date.now() - waitStart;
    if (!(await reviewRegion.count())) await generate.click();
    stage = 'review-visible';
    await reviewRegion.waitFor();
    stage = 'review-label';
    await reviewRegion.getByText('UNAPPROVED RESEARCH — NOT PRODUCTION REGULATORY GUIDANCE').waitFor();
    const hash = await reviewRegion.locator('p.hash code').textContent();
    assert.match(hash, /^[a-f0-9]{64}$/);
    stage = 'review-approve-button';
    const approveButton = reviewRegion.getByRole('button', { name: 'Approve & Run Once', exact: true });
    await approveButton.waitFor();
    assert.equal(await approveButton.isDisabled(), false);
    stage = 'review-preview';
    await reviewRegion.locator('summary').filter({ hasText: 'Complete request' }).click();
    assert.ok((await reviewRegion.locator('pre.request-preview').textContent()).includes('claude-sonnet-5-5'));
    await page.screenshot({ path: path.join(output, 'ai-request-review-desktop.png'), fullPage: true });
    report.ai_request_review_visible = true;
    report.request_sha256 = hash;
    stage = 'review-refresh';
    await page.reload();
    await page.getByRole('region', { name: 'AI Request Review', exact: true }).waitFor();
    assert.equal(await page.getByRole('region', { name: 'AI Request Review', exact: true }).locator('p.hash code').textContent(), hash);
    report.review_survives_refresh_same_hash = true;
    report.controlled_claude_approval_gate_visible = true;
    const summary = region.locator('summary').filter({ hasText: '31 CFR § 1020.320' });
    await summary.click();
    const href = await region.getByRole('link', { name: 'Open historical eCFR source' }).getAttribute('href');
    assert.ok(href.startsWith('https://www.ecfr.gov/api/versioner/v1/full/2026-11-02/title-31.xml'));
    assert.ok((await region.textContent()).includes('Suspicious'));
    await page.screenshot({ path: path.join(output, 'research-desktop.png'), fullPage: true });
    report.real_research_text_and_historical_link = true;
    stage = 'refresh';
    await page.reload();
    await page.getByRole('region', { name: 'Regulatory Research / Unapproved', exact: true }).getByText(notice, { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Username', { exact: true }).count(), 0);
    report.refresh_preserves_research_and_session = true;
    stage = 'human-controls';
    await page.goto(`${base}/#/cases/${caseId}/casework`);
    await page.getByRole('form', { name: 'Investigation Notes', exact: true }).waitFor();
    report.human_casework_available = true;
    await page.setViewportSize({ width: 1024, height: 768 });
    await page.goto(`${base}/#/cases/${caseId}/investigation`);
    await page.getByRole('region', { name: 'Regulatory Research / Unapproved', exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'research-tablet.png'), fullPage: true });
    stage = 'cross-user';
    const login = await api.post('/api/v1/auth/token', { data: { username: 'windowsanalyst', password: logins.windowsanalyst.password } });
    assert.equal(login.status(), 200);
    const token = (await login.json()).access_token;
    const denied = await api.get(`/api/v1/cases/${caseId}/investigation-drafts/research-context/latest`, { headers: { Authorization: `Bearer ${token}` } });
    assert.ok([403, 404].includes(denied.status()));
    report.wrong_user_denied = true;
    stage = 'logout';
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await page.getByLabel('Username', { exact: true }).waitFor();
    assert.equal(await page.evaluate(async id => (await fetch(`/api/v1/cases/${id}/investigation-drafts/research-context/latest`)).status, caseId), 401);
    report.logout_denied = true;
    report.status = 'research-preflight-browser-passed-awaiting-owner-approval-in-react';
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify({ ...report, screenshots: output }));
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true });
    throw error;
  } finally { await api.dispose(); await context.close(); await browser.close(); }
})().catch(error => {
  fs.writeFileSync(path.join(output, 'failure.json'), JSON.stringify({ stage, error_type: error.name, live_requests: 0 }));
  console.log(JSON.stringify({ status: 'failed', stage, error_type: error.name, live_requests: 0, screenshots: output }));
  process.exitCode = 1;
});
